//! Embedded 8x8 bitmap font, printable ASCII 32..=126.
//!
//! The UI core never asks the OS for fonts — on some device there *is* no
//! OS font service (and on principle we don't phone one). Glyphs are
//! authored as readable row-strings (`#` = pixel) and packed by a `const fn`
//! at compile time. Bit 7 of each row byte is the leftmost pixel.

/// Pack 8 rows of 8 chars into 8 bytes. `const` so the table costs nothing
/// at runtime.
const fn glyph(rows: [&str; 8]) -> [u8; 8] {
    let mut out = [0u8; 8];
    let mut r = 0;
    while r < 8 {
        let b = rows[r].as_bytes();
        let mut v = 0u8;
        let mut c = 0;
        while c < 8 {
            v <<= 1;
            if b[c] == b'#' {
                v |= 1;
            }
            c += 1;
        }
        out[r] = v;
        r += 1;
    }
    out
}

