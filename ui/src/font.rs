/// Bitmap for a printable ASCII char: 8 rows, bit 7 = leftmost pixel.
/// Anything outside 32..=126 renders as space.
pub fn glyph_for(ch: char) -> [u8; 8] {
    let c = ch as u32;
    if (32..96).contains(&c) {
        GLYPHS[(c - 32) as usize]
    } else if (96..=126).contains(&c) {
        GLYPHS2[(c - 96) as usize]
    } else {
        GLYPHS[0]
    }
}

