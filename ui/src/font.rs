#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_covers_all_printable_ascii() {
        for c in 32u32..=126 {
            let g = glyph_for(char::from_u32(c).unwrap());
            // Space is the only all-blank glyph.
            if c == 32 {
                assert_eq!(g, [0; 8]);
            } else {
                assert_ne!(g, [0; 8], "glyph {} is blank", c);
            }
        }
    }

    #[test]
    fn out_of_range_renders_as_space() {
        assert_eq!(glyph_for('é'), GLYPHS[0]);
        assert_eq!(glyph_for('\n'), GLYPHS[0]);
    }

    #[test]
    fn const_fn_packs_bits_left_to_right() {
        let g = glyph([
            "#.......", "........", "........", "........", "........", "........", "........",
            "........",
        ]);
        assert_eq!(g[0], 0b1000_0000);
    }
}
